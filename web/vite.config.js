import { defineConfig } from 'vite';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

// The app lives in web/, but the precomputed NASA data (data/) and the EIC
// cover art (assets/) live at the repo root so the Python pipeline and the
// browser share one source of truth. Allow Vite to serve/bundle from there.
const repoRoot = fileURLToPath(new URL('..', import.meta.url));

// Works offline: after the first visit a service worker has cached the app
// and every frame of data, so a classroom or kiosk with weak internet can
// still play it. The worker's file list is written at build time from the
// bundle itself, so it can never miss an asset or keep a stale one.
const PUBLIC_FILES = ['./', 'index.html', 'manifest.webmanifest', 'icon-192.png', 'icon-512.png'];

function offline() {
  return {
    name: 'terra-vox-offline',
    apply: 'build',
    generateBundle(_, bundle) {
      const files = [...PUBLIC_FILES, ...Object.keys(bundle).filter((f) => !f.endsWith('.map'))];
      // Hash names and contents: index.html keeps its name when only its markup changes.
      const hash = createHash('sha256').update(files.join('\n'));
      for (const f of Object.keys(bundle).sort()) hash.update(bundle[f].code ?? bundle[f].source ?? '');
      const version = hash.digest('hex').slice(0, 12);
      const source = `// Generated by vite.config.js (terra-vox-offline). Do not edit.
const CACHE = 'terra-vox-${version}';
const FILES = ${JSON.stringify(files)};

self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys()
    .then((keys) => Promise.all(keys.filter((k) => k.startsWith('terra-vox-') && k !== CACHE).map((k) => caches.delete(k))))
    .then(() => self.clients.claim()));
});

// The page itself is network first, so a returning visitor gets a new deploy on
// the first load; offline it falls back to the cached app shell. Everything
// else is versioned by its hash, so it is cache first.
self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;
  if (req.mode === 'navigate') {
    e.respondWith(fetch(req).catch(() => caches.match('index.html')));
    return;
  }
  e.respondWith(caches.match(req).then((hit) => hit ?? fetch(req)));
});
`;
      this.emitFile({ type: 'asset', fileName: 'sw.js', source });
    },
  };
}

export default defineConfig({
  root: '.',
  base: './',
  server: {
    port: 5173,
    fs: { allow: [repoRoot] },
  },
  build: {
    outDir: 'dist',
    assetsInlineLimit: 0,
    chunkSizeWarningLimit: 1200,
  },
  plugins: [offline()],
});
